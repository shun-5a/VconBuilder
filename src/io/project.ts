import { AGENTS_FILE, CLAUDE_FILE, isGeneratedClaudeMd, mergeAgentsMd } from "../model/agentsDoc";
import { parseProject, serializeProject } from "../model/serialize";
import { emptyProject } from "../model/template";
import { useStore } from "../store/store";
import {
  copyProject,
  createUntitledDir,
  discardUntitled,
  ensureProjectDirs,
  fileExists,
  isUntitledDir,
  joinPath,
  listAssets,
  listUntitled,
  onAssetsChanged,
  onProjectFileChanged,
  openProjectDir,
  projectFile,
  readText,
  removeFile,
  stopWatchingDir,
  takeOpenDir,
  writeTextAtomic,
} from "./backend";

const SAVE_DELAY_MS = 300;
const SAVE_RETRY_MS = 3000;
const RECENTS_KEY = "vcon.recentProjects";

/** Last text we wrote or read, so our own writes coming back through the watcher are ignored. */
let lastText = "";
/** Path of the open project's file (`<folder name>.vcb`). */
let filePath = "";
let saveTimer: ReturnType<typeof setTimeout> | undefined;
let retryTimer: ReturnType<typeof setTimeout> | undefined;
let unlisten: Array<() => void> = [];

export function getRecentProjects(): string[] {
  try {
    return JSON.parse(localStorage.getItem(RECENTS_KEY) ?? "[]");
  } catch {
    return [];
  }
}

function pushRecent(dir: string) {
  try {
    const list = [dir, ...getRecentProjects().filter((d) => d !== dir)].slice(0, 10);
    localStorage.setItem(RECENTS_KEY, JSON.stringify(list));
  } catch {
    // storage unavailable – recents are a convenience only
  }
}

/**
 * AGENTS.md: refreshes the generated guide block (user notes outside it are kept).
 * CLAUDE.md is not created any more; one generated by an earlier version is removed.
 */
async function writeAgentGuides(dir: string) {
  const agentsPath = joinPath(dir, AGENTS_FILE);
  const current = (await fileExists(agentsPath)) ? await readText(agentsPath) : null;
  const next = mergeAgentsMd(current);
  if (next !== current) await writeTextAtomic(agentsPath, next);

  const claudePath = joinPath(dir, CLAUDE_FILE);
  if ((await fileExists(claudePath)) && isGeneratedClaudeMd(await readText(claudePath))) await removeFile(claudePath);
}

/** Opens `dir`; creates a new project there when it has no project file yet. */
export async function openOrCreateProject(dir: string): Promise<void> {
  const untitled = await isUntitledDir(dir);
  const projectPath = await projectFile(dir);
  await ensureProjectDirs(dir);
  if (!(await fileExists(projectPath))) {
    const text = serializeProject(emptyProject());
    await writeTextAtomic(projectPath, text);
  }
  const text = await readText(projectPath);
  const parsed = parseProject(text);
  if (!parsed.ok) throw new Error(`${projectPath.split(/[\\/]/).pop()} could not be loaded\n${parsed.error}`);

  await writeAgentGuides(dir);

  stopWatching();
  lastText = text;
  filePath = projectPath;
  useStore.getState().setProject(dir, parsed.project, untitled);
  await openProjectDir(dir);
  await refreshAssets();
  unlisten = [await onProjectFileChanged(debounce(reloadFromDisk, 150)), await onAssetsChanged(debounce(refreshAssets, 200))];
  if (!untitled) pushRecent(dir);
}

export function stopWatching() {
  for (const u of unlisten) u();
  unlisten = [];
}

export async function refreshAssets() {
  const dir = useStore.getState().dir;
  if (!dir) return;
  useStore.setState({ assets: await listAssets(dir) });
}

async function reloadFromDisk() {
  if (!useStore.getState().dir) return;
  let text: string;
  try {
    text = await readText(filePath);
  } catch {
    return; // file is being replaced; the next event will catch up
  }
  if (text === lastText) {
    // e.g. a broken edit was reverted to what we already have
    if (useStore.getState().loadError) useStore.setState({ loadError: null });
    return;
  }
  if (useStore.getState().saveError) {
    // Local changes are not on disk yet; replacing them with the file would lose them.
    useStore.setState({ notice: "The project file changed outside the app, but local changes are not saved yet; keeping them" });
    return;
  }
  const parsed = parseProject(text);
  if (!parsed.ok) {
    useStore.setState({ loadError: parsed.error });
    return;
  }
  lastText = text;
  if (saveTimer) {
    // A local edit was still waiting to be saved; the external version wins and the local one stays in undo history.
    clearTimeout(saveTimer);
    saveTimer = undefined;
  }
  useStore.getState().replaceFromDisk(parsed.project);
}

/**
 * Writes the project if it changed; returns whether the file is now up to date.
 * Never writes a project the file format would reject (it could not be opened again). A failed write
 * is retried every few seconds, and `saveError` stays set until a save succeeds.
 */
export async function saveNow(): Promise<boolean> {
  clearTimeout(saveTimer);
  clearTimeout(retryTimer);
  saveTimer = retryTimer = undefined;
  const { dir, project } = useStore.getState();
  if (!dir || !project) return true;
  const text = serializeProject(project);
  const setError = (saveError: string | null) => {
    if (useStore.getState().saveError !== saveError) useStore.setState({ saveError });
  };
  if (text === lastText) {
    setError(null);
    return true;
  }
  const check = parseProject(text);
  if (!check.ok) {
    setError(`Not saved: the project contains invalid values (undo the last change)
${check.error}`);
    return false;
  }
  try {
    await writeTextAtomic(filePath, text);
    lastText = text;
    setError(null);
    return true;
  } catch (e) {
    setError(`Save failed, retrying: ${e instanceof Error ? e.message : e}`);
    retryTimer = setTimeout(saveNow, SAVE_RETRY_MS);
    return false;
  }
}

/** Stops pending / retried saves (when leaving the project). */
function cancelPendingSaves() {
  clearTimeout(saveTimer);
  clearTimeout(retryTimer);
  saveTimer = retryTimer = undefined;
}

/** Saves shortly after every local edit (the JSON file is always the source of truth). */
export function startAutosave(): () => void {
  return useStore.subscribe((s, prev) => {
    if (s.revision === prev.revision || !s.project) return;
    if (saveTimer) clearTimeout(saveTimer);
    saveTimer = setTimeout(saveNow, SAVE_DELAY_MS);
  });
}

function debounce(fn: () => void, ms: number) {
  let t: ReturnType<typeof setTimeout> | undefined;
  return () => {
    if (t) clearTimeout(t);
    t = setTimeout(fn, ms);
  };
}

// ------------------------------------------------------------------ untitled projects / save to folder

/** Starts a new, empty untitled project (stored in the app data folder until "Save to folder…"). */
export async function newUntitledProject() {
  await openOrCreateProject(await createUntitledDir());
}

/**
 * On launch: a double-clicked .vcb opens its project. Otherwise an untitled folder left behind means the
 * app did not close normally (closing asks to save or deletes it), so recover it; else start a new project.
 */
export async function openStartupProject() {
  const requested = await takeOpenDir();
  if (requested) {
    await openOrCreateProject(requested);
    return;
  }
  const [latest] = await listUntitled();
  if (latest) {
    await openOrCreateProject(latest);
    if (hasContent())
      useStore.setState({
        notice: "Recovered an unsaved project from a session that did not close normally. Use File ▸ Save to folder… to keep it.",
      });
  } else {
    await newUntitledProject();
  }
}

/** Whether the current project holds anything worth keeping (clips, assets or edits). */
export function hasContent(): boolean {
  const { project, assets, past } = useStore.getState();
  if (!project) return false;
  return past.length > 0 || assets.length > 0 || project.tracks.some((t) => t.clips.length > 0);
}

async function leaveCurrent() {
  await saveNow();
  cancelPendingSaves();
  stopWatching();
  await stopWatchingDir();
}

/** Flushes and stops watching the current project; an untitled one is deleted with its temporary files. */
export async function releaseCurrentProject() {
  const { dir, untitled } = useStore.getState();
  if (!dir) return;
  await leaveCurrent();
  if (untitled) await discardUntitled(dir).catch(() => {});
}

/**
 * Untitled project: moves it (project file + assets) into `target` and continues working there.
 * Saved project: writes a copy to `target` and keeps working on the original.
 * (There is no "save" otherwise: every change is written to the project file immediately.)
 */
export async function saveProjectTo(target: string) {
  const { dir, untitled } = useStore.getState();
  if (!dir) return;
  if (!untitled) {
    await saveNow();
    await copyProject(dir, target);
    useStore.setState({ notice: `Saved a copy to ${target}` });
    return;
  }
  await leaveCurrent();
  try {
    await copyProject(dir, target);
  } catch (e) {
    await openOrCreateProject(dir); // keep working where we were
    throw e;
  }
  await discardUntitled(dir).catch(() => {});
  await openOrCreateProject(target);
  useStore.setState({ notice: `Saved to ${target}` });
}
