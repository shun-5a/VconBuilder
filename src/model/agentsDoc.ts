/**
 * Returns the AGENTS.md text: the generated guide between markers, keeping whatever the user wrote
 * outside them (or appending the guide to a file that has no markers yet).
 */
export function mergeAgentsMd(existing: string | null): string {
  const block = `${BEGIN}\n${GUIDE.trim()}\n${END}`;
  if (!existing?.trim()) {
    return `${block}\n\n## Project notes\n\n<!-- Notes for agents about this particular project (kept by VconBuilder). -->\n`;
  }
  const a = existing.indexOf(BEGIN);
  const b = existing.indexOf(END);
  if (a >= 0 && b > a) return existing.slice(0, a) + block + existing.slice(b + END.length);
  return `${existing.trimEnd()}\n\n${block}\n`;
}
